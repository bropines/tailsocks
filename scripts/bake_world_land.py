#!/usr/bin/env python3
"""Bakes the world outline the exit-node map draws.

Input: Natural Earth 1:110m land polygons (public domain, naturalearthdata.com),
  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
Output: app/src/main/java/io/github/bropines/tailscaled/ui/WorldLandPath.kt, an SVG
path string (`M lon lat lon lat ... Z` per ring, degrees, latitude up) that
ui/WorldLand.kt reads. Source code, not a blob: F-Droid's scanner rejects
binaries. Outer rings only, simplified, specks dropped: the map is a
phone-sized backdrop for a few dots, not cartography.

    python3 scripts/bake_world_land.py ne_110m_land.geojson
"""
import json, sys

TOLERANCE_DEG = 0.35   # Douglas-Peucker; below what a 360 dp wide map can show
MIN_AREA_DEG2 = 6.0    # islands smaller than this are a pixel or less
MIN_LAT = -60.0        # Antarctica only stretches the map

def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay
        norm = (dx * dx + dy * dy) ** 0.5 or 1e-12
        worst, at = 0.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / norm
            if d > worst:
                worst, at = d, i
        if worst > tol and at > 0:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(pts, keep) if k]

def area(pts):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(pts, pts[1:] + pts[:1]))) / 2

def main():
    src = json.load(open(sys.argv[1]))
    rings = []
    for feature in src["features"]:
        g = feature["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            outer = [(float(x), float(y)) for x, y in poly[0]]
            if max(y for _, y in outer) < MIN_LAT or area(outer) < MIN_AREA_DEG2:
                continue
            # A closed ring starts where it ends, which gives Douglas-Peucker no
            # baseline: cut it at the point farthest from the start and do each half.
            if outer[0] == outer[-1]:
                outer = outer[:-1]
            far = max(range(len(outer)), key=lambda i: (outer[i][0] - outer[0][0]) ** 2 + (outer[i][1] - outer[0][1]) ** 2)
            ring = simplify(outer[:far + 1], TOLERANCE_DEG)[:-1] + simplify(outer[far:] + outer[:1], TOLERANCE_DEG)[:-1]
            if len(ring) >= 4:
                rings.append(ring)
    rings.sort(key=area, reverse=True)
    def deg(v, lim):
        return f"{round(max(-lim, min(lim, v)) * 100) / 100:g}"
    parts = ["M" + " ".join(f"{deg(x, 180)} {deg(y, 90)}" for x, y in ring) + "Z" for ring in rings]
    out = "\n".join([
        "// Generated by scripts/bake_world_land.py from Natural Earth 1:110m land (public domain).",
        "// Do not edit by hand. One ring per line: an SVG path in degrees, latitude up.",
        "package io.github.bropines.tailscaled.ui",
        "",
        "internal const val WORLD_LAND_PATH =",
        " +\n".join(f'    "{p}"' for p in parts),
        "",
    ])
    dest = "app/src/main/java/io/github/bropines/tailscaled/ui/WorldLandPath.kt"
    open(dest, "w").write(out)
    print(f"{len(rings)} rings, {sum(map(len, rings))} points, {len(out)} chars -> {dest}")

if __name__ == "__main__":
    main()
